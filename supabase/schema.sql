-- Schema do painel de produtos da Pink Acessorium
-- Rodar isso PRIMEIRO no SQL Editor do Supabase, depois o migration.sql.

create table produtos (
  id          bigint generated by default as identity primary key,
  cod         text not null unique,
  nome        text not null,
  cat         text not null,
  preco       numeric not null default 0,
  de          numeric not null default 0,
  tag         text not null default '',
  img         text,
  imgs        jsonb,
  pos         text,
  sizes       jsonb,
  letras      jsonb,
  cores       jsonb,
  cats_extra  jsonb,
  estoque     integer,
  ativo       boolean not null default true,
  data        date,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index produtos_cat_idx on produtos (cat);

create or replace function set_updated_at() returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

create trigger produtos_set_updated_at
  before update on produtos
  for each row execute function set_updated_at();

alter table produtos enable row level security;

create policy "produtos_leitura_publica"
  on produtos for select
  using (true);

create policy "produtos_escrita_autenticada"
  on produtos for all
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

insert into storage.buckets (id, name, public)
values ('fotos-novas', 'fotos-novas', true)
on conflict (id) do nothing;

create policy "fotos_novas_leitura_publica"
  on storage.objects for select
  using (bucket_id = 'fotos-novas');

create policy "fotos_novas_escrita_autenticada"
  on storage.objects for all
  using (bucket_id = 'fotos-novas' and auth.role() = 'authenticated')
  with check (bucket_id = 'fotos-novas' and auth.role() = 'authenticated');
